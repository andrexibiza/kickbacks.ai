impl InstallSelection {
    fn resolve(&self) -> Targets {
        let default_all = !self.all
            && !self.vscode
            && !self.claude_cli
            && !self.codex_cli
            && !self.hermes
            && !self.skills;
        Targets {
            vscode: default_all || self.all || self.vscode,
            claude_cli: default_all || self.all || self.claude_cli,
            codex_cli: default_all || self.all || self.codex_cli,
            hermes: default_all || self.all || self.hermes,
            skills: default_all
                || self.all
                || self.skills
                || self.claude_cli
                || self.codex_cli
                || self.hermes,
        }
    }
}


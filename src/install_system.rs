fn write_marker_file(path: &Path, content: &str) -> Result<()> {
    let backup_path = backup_record_path()?;
    write_marker_file_with_backup(path, content, &backup_path)
}

fn write_marker_file_with_backup(path: &Path, content: &str, backup_path: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    let new_bytes = content.as_bytes();
    if path.exists() {
        let existing = fs::read(path).with_context(|| format!("reading {}", path.display()))?;
        if !String::from_utf8_lossy(&existing).contains(MARKER) {
            anyhow::bail!(
                "{} exists and was not created by kickbacks-kit; refusing to overwrite",
                path.display()
            );
        }
        if existing == new_bytes {
            return Ok(());
        }
        record_marker_backup(path, &existing, backup_path)?;
    }
    fs::write(path, new_bytes).with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}

#[derive(Default)]
struct RestoreReport {
    restored: usize,
    removed: usize,
    kept: usize,
    missing: usize,
}

fn restore_marker_file(path: &Path, report: &mut RestoreReport) -> Result<()> {
    let backup_path = backup_record_path()?;
    restore_marker_file_with_backup(path, report, &backup_path)
}

fn restore_marker_file_with_backup(
    path: &Path,
    report: &mut RestoreReport,
    backup_path: &Path,
) -> Result<()> {
    if !path.exists() {
        report.missing += 1;
        return Ok(());
    }

    let existing = fs::read(path).with_context(|| format!("reading {}", path.display()))?;
    if String::from_utf8_lossy(&existing).contains(MARKER) {
        if let Some(record) = last_backup_for_path(backup_path, path)? {
            let bytes = hex_decode(&record.bytes_hex)?;
            anyhow::ensure!(
                sha256_hex(&bytes) == record.sha256,
                "backup checksum mismatch for {}",
                path.display()
            );
            fs::write(path, bytes).with_context(|| format!("restoring {}", path.display()))?;
            report.restored += 1;
            println!("  {} restored {}", "ok".green(), path.display());
        } else {
            fs::remove_file(path).with_context(|| format!("removing {}", path.display()))?;
            report.removed += 1;
            println!("  {} removed {}", "ok".green(), path.display());
        }
    } else {
        report.kept += 1;
        println!("  {} kept non-marker file {}", "*".yellow(), path.display());
    }
    Ok(())
}

#[derive(Debug, Clone, Deserialize, Serialize)]
struct BackupRecord {
    path: String,
    sha256: String,
    bytes_hex: String,
}

fn backup_record_path() -> Result<PathBuf> {
    Ok(paths::data_dir()?.join("install-backups.jsonl"))
}

fn record_marker_backup(path: &Path, bytes: &[u8], backup_path: &Path) -> Result<()> {
    if let Some(parent) = backup_path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    let record = BackupRecord {
        path: path_key(path),
        sha256: sha256_hex(bytes),
        bytes_hex: hex_encode(bytes),
    };
    let mut file = fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(backup_path)
        .with_context(|| format!("opening {}", backup_path.display()))?;
    let line = serde_json::to_string(&record)?;
    writeln!(file, "{line}").with_context(|| format!("writing {}", backup_path.display()))?;
    Ok(())
}

fn last_backup_for_path(backup_path: &Path, path: &Path) -> Result<Option<BackupRecord>> {
    if !backup_path.exists() {
        return Ok(None);
    }
    let target = path_key(path);
    let raw = fs::read_to_string(backup_path)
        .with_context(|| format!("reading {}", backup_path.display()))?;
    let mut found = None;
    for line in raw.lines().filter(|line| !line.trim().is_empty()) {
        let record: BackupRecord = serde_json::from_str(line)
            .with_context(|| format!("parsing {}", backup_path.display()))?;
        if record.path == target {
            found = Some(record);
        }
    }
    Ok(found)
}

fn path_key(path: &Path) -> String {
    path.canonicalize()
        .unwrap_or_else(|_| path.to_path_buf())
        .display()
        .to_string()
}

fn sha256_hex(bytes: &[u8]) -> String {
    hex_encode(&Sha256::digest(bytes))
}

fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(HEX[(byte >> 4) as usize] as char);
        out.push(HEX[(byte & 0x0f) as usize] as char);
    }
    out
}

fn hex_decode(raw: &str) -> Result<Vec<u8>> {
    anyhow::ensure!(raw.len() % 2 == 0, "invalid hex length");
    let bytes = raw.as_bytes();
    let mut out = Vec::with_capacity(raw.len() / 2);
    let mut i = 0;
    while i < bytes.len() {
        let high = hex_value(bytes[i])?;
        let low = hex_value(bytes[i + 1])?;
        out.push((high << 4) | low);
        i += 2;
    }
    Ok(out)
}

fn hex_value(byte: u8) -> Result<u8> {
    match byte {
        b'0'..=b'9' => Ok(byte - b'0'),
        b'a'..=b'f' => Ok(byte - b'a' + 10),
        b'A'..=b'F' => Ok(byte - b'A' + 10),
        _ => anyhow::bail!("invalid hex byte"),
    }
}

fn remove_empty_dir(path: &Path) -> Result<()> {
    if path.exists() {
        match fs::remove_dir(path) {
            Ok(()) => {}
            Err(err) if is_directory_not_empty(&err) => {}
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {}
            Err(err) => return Err(err).with_context(|| format!("removing {}", path.display())),
        }
    }
    Ok(())
}

fn is_directory_not_empty(err: &std::io::Error) -> bool {
    matches!(err.raw_os_error(), Some(145 | 39 | 17))
}


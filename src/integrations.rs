fn claude_status() -> IntegrationStatus {
    let exe = find_executable("claude");
    let home = dirs::home_dir();
    let settings = home
        .as_ref()
        .map(|h| h.join(".claude").join("settings.json"));
    let statusline_enabled = settings
        .as_ref()
        .and_then(|p| std::fs::read_to_string(p).ok())
        .map(|s| claude_statusline_enabled(&s))
        .unwrap_or(false);
    let command_paths = home
        .as_ref()
        .map(|h| claude_command_paths(h))
        .unwrap_or_default();
    let commands_owned = all_marker_owned(&command_paths);
    let skill = home.as_ref().map(|h| {
        h.join(".claude")
            .join("skills")
            .join("kickbacks")
            .join("SKILL.md")
    });
    let skill_owned = skill
        .as_ref()
        .map(|p| install_state(p) == InstallState::MarkerOwned)
        .unwrap_or(false);
    let enabled = statusline_enabled && commands_owned && skill_owned;
    let detected = exe.is_some()
        || settings.as_ref().map(|p| p.exists()).unwrap_or(false)
        || command_paths.iter().any(|p| p.exists())
        || skill.as_ref().map(|p| p.exists()).unwrap_or(false);
    IntegrationStatus {
        id: "claude",
        label: "Claude Code CLI",
        kind: "cli",
        detected,
        enabled,
        capability: if enabled {
            IntegrationCapability::Earn
        } else {
            IntegrationCapability::Configure
        },
        version: tool_version("claude"),
        path: exe.map(|p| p.display().to_string()),
        detail: if enabled {
            "Claude statusLine, slash commands, and skill are marker-owned".to_string()
        } else if statusline_enabled {
            "Claude statusLine is wired; run repair to add marker-owned commands and skill"
                .to_string()
        } else if detected {
            "Claude found; run the installer to add statusLine, slash commands, and skill"
                .to_string()
        } else {
            "Run the installer to add statusLine, slash commands, and skill".to_string()
        },
        install_command: "kickbacks install --claude-cli --skills".to_string(),
        repair_command: "kickbacks repair --claude-cli".to_string(),
    }
}


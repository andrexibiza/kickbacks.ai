fn install_state(path: &Path) -> InstallState {
    if !path.exists() {
        return InstallState::Missing;
    }
    match std::fs::read_to_string(path) {
        Ok(content) if content.contains(MARKER) => InstallState::MarkerOwned,
        _ => InstallState::Foreign,
    }
}

fn install_state_detail(path: &Path, noun: &str) -> String {
    match install_state(path) {
        InstallState::Missing => format!("{noun} not installed"),
        InstallState::MarkerOwned => format!("{noun} installed by kickbacks-kit"),
        InstallState::Foreign => {
            format!("{noun} exists but is not marker-owned; repair will not overwrite it")
        }
    }
}

fn all_marker_owned(paths: &[PathBuf]) -> bool {
    !paths.is_empty()
        && paths
            .iter()
            .all(|path| install_state(path) == InstallState::MarkerOwned)
}


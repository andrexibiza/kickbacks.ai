fn claude_statusline_enabled(raw_settings: &str) -> bool {
    let parsed = serde_json::from_str::<serde_json::Value>(raw_settings)
        .ok()
        .and_then(|v| {
            v.get("statusLine")
                .and_then(|s| s.get("command"))
                .and_then(|c| c.as_str())
                .map(str::to_string)
        });
    parsed
        .as_deref()
        .map(command_is_kickbacks_statusline)
        .unwrap_or_else(|| {
            raw_settings.contains("kb statusline") || raw_settings.contains("kickbacks statusline")
        })
}

fn command_is_kickbacks_statusline(command: &str) -> bool {
    command.contains("kb statusline")
        || command.contains("kickbacks statusline")
        || (command.contains("kb.exe") && command.contains("statusline"))
        || (command.contains("kickbacks.exe") && command.contains("statusline"))
}

fn installed_extension_dir_from(exts_dir: &Path) -> Option<PathBuf> {
    let entries = std::fs::read_dir(exts_dir).ok()?;
    entries
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| extension_version(p).is_some())
        .max_by(|a, b| compare_extension_paths(a, b))
}

fn compare_extension_paths(a: &Path, b: &Path) -> Ordering {
    match (extension_version(a), extension_version(b)) {
        (Some(left), Some(right)) => compare_versions(&left, &right),
        (Some(_), None) => Ordering::Greater,
        (None, Some(_)) => Ordering::Less,
        (None, None) => Ordering::Equal,
    }
}

fn extension_version(path: &Path) -> Option<String> {
    path.file_name()
        .and_then(|n| n.to_str())
        .and_then(|n| n.strip_prefix("kickbacksai.kickbacks-ai-"))
        .map(str::to_string)
}

fn compare_versions(a: &str, b: &str) -> Ordering {
    let a_parts = version_parts(a);
    let b_parts = version_parts(b);
    for i in 0..a_parts.len().max(b_parts.len()) {
        let left = *a_parts.get(i).unwrap_or(&0);
        let right = *b_parts.get(i).unwrap_or(&0);
        match left.cmp(&right) {
            Ordering::Equal => {}
            ord => return ord,
        }
    }
    a.cmp(b)
}

fn version_parts(version: &str) -> Vec<u64> {
    version
        .split(|c: char| !c.is_ascii_digit())
        .filter(|part| !part.is_empty())
        .filter_map(|part| part.parse::<u64>().ok())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::time::{SystemTime, UNIX_EPOCH};

    struct TempDir(PathBuf);

    impl TempDir {
        fn new(name: &str) -> Self {
            let stamp = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos();
            let dir = env::temp_dir().join(format!(
                "kb-integrations-{name}-{}-{stamp}",
                std::process::id()
            ));
            fs::create_dir_all(&dir).unwrap();
            Self(dir)
        }

        fn path(&self) -> &Path {
            &self.0
        }
    }

    impl Drop for TempDir {
        fn drop(&mut self) {
            fs::remove_dir_all(&self.0).ok();
        }
    }

    #[test]
    fn install_state_requires_marker() {
        let dir = TempDir::new("marker");
        let missing = dir.path().join("missing.md");
        assert_eq!(install_state(&missing), InstallState::Missing);

        let foreign = dir.path().join("foreign.md");
        fs::write(&foreign, "name: kickbacks").unwrap();
        assert_eq!(install_state(&foreign), InstallState::Foreign);

        let owned = dir.path().join("owned.md");
        fs::write(&owned, format!("<!-- {MARKER} -->")).unwrap();
        assert_eq!(install_state(&owned), InstallState::MarkerOwned);
    }

    #[test]
    fn extension_detection_uses_numeric_version_order() {
        let dir = TempDir::new("extensions");
        fs::create_dir_all(dir.path().join("kickbacksai.kickbacks-ai-0.3.99")).unwrap();
        fs::create_dir_all(dir.path().join("kickbacksai.kickbacks-ai-0.3.174")).unwrap();
        fs::create_dir_all(dir.path().join("unrelated.extension-9.9.9")).unwrap();

        let found = installed_extension_dir_from(dir.path()).unwrap();
        assert_eq!(extension_version(&found).as_deref(), Some("0.3.174"));
    }

    #[test]
    fn claude_statusline_detection_parses_json_and_exe_paths() {
        assert!(claude_statusline_enabled(
            r#"{"statusLine":{"command":"\"C:\\tools\\kickbacks.exe\" statusline"}}"#
        ));
        assert!(claude_statusline_enabled("kb statusline"));
        assert!(!claude_statusline_enabled(
            r#"{"statusLine":{"command":"custom-status.sh"}}"#
        ));
    }
}
